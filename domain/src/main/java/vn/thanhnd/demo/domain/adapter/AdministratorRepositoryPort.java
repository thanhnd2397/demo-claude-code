package vn.thanhnd.demo.domain.adapter;

import vn.thanhnd.demo.domain.enums.AdministratorStatus;
import vn.thanhnd.demo.domain.model.Administrator;
import vn.thanhnd.demo.domain.model.AdministratorPermissionsCacheData;

import java.util.List;
import java.util.Optional;
import java.util.Set;

/**
 * Port for {@link Administrator} persistence.
 */
public interface AdministratorRepositoryPort {

    /**
     * Find an administrator by exact username.
     *
     * @param username The username to look up
     * @return The matching administrator, or empty if none exists
     */
    Optional<Administrator> findByUsername(String username);

    /**
     * Find an administrator by exact username or exact email.
     *
     * @param identifier The username or email to look up
     * @return The matching administrator, or empty if none exists
     */
    Optional<Administrator> findByUsernameOrEmail(String identifier);

    /**
     * Find an administrator by id.
     *
     * @param id The administrator's id
     * @return The matching administrator, or empty if none exists
     */
    Optional<Administrator> findById(String id);

    /**
     * Check whether an administrator with the given username already exists.
     *
     * @param username The username to check
     * @return true if the username is already taken
     */
    boolean existsByUsername(String username);

    /**
     * Check whether an administrator with the given email already exists.
     *
     * @param email The email to check
     * @return true if the email is already taken
     */
    boolean existsByEmail(String email);

    /**
     * Persist a new administrator, resolving its role names to stored roles.
     *
     * @param administrator The administrator to insert (id is generated by the database)
     * @return The persisted administrator including its generated id
     */
    Administrator save(Administrator administrator);

    /**
     * Retrieve all administrators with their role and permission names.
     *
     * @return All administrators; empty list if none exist
     */
    List<Administrator> findAll();

    /**
     * Replace an administrator's entire role set with the given role names (full replace, not a merge).
     *
     * @param administratorId The target administrator's id
     * @param roleNames The complete new set of role names
     * @return The updated administrator
     * @throws vn.thanhnd.demo.domain.exception.DomainValidationException if {@code administratorId} does not
     *                                                                    exist, or if {@code roleNames} contains an unknown role
     */
    Administrator updateRoles(String administratorId, Set<String> roleNames);

    /**
     * Change an administrator's lifecycle status.
     *
     * @param administratorId The target administrator's id
     * @param status The new status
     * @return The updated administrator
     * @throws vn.thanhnd.demo.domain.exception.DomainValidationException if {@code administratorId} does not exist
     */
    Administrator updateStatus(String administratorId, AdministratorStatus status);

    /**
     * Fetch the administrator's current role and permission names, cache-aside via Redis.
     *
     * @param administratorId The administrator's id
     * @return The current role and permission names
     * @throws vn.thanhnd.demo.domain.exception.DomainValidationException if {@code administratorId} does not exist
     */
    AdministratorPermissionsCacheData findPermissions(String administratorId);
}
